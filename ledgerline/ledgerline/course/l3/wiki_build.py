"""Lecture 3, the LLM Wiki: INGEST. Northbridge's 699-file dump compiled into linked, cited wiki pages.

    from ledgerline.course.l3 import wiki_build as WB
    report = WB.build(dump_root, out_dir, llm)            # read every source, write every page, index.md, log.md
    report = WB.update(["08_release_notes/RN-7.2.3-P6 ….pdf"], dump_root, out_dir, llm)   # absorb one new source

The ingest in four passes (each pass parallel; each LLM call recorded to the cassette):
  1. READ    one call per source part: what the source is, which pages it touches, the facts for each page with a
             verbatim quote and its location (page / section / sheet / row). The prompt carries AGENTS.md and the
             registry of canonical slugs seeded from Northbridge's own codes (wiki_sources.build_registry).
  2. MERGE   slugs are canonicalised by code (codes, names, prefixes); one call merges near-duplicate new topics.
  3. WRITE   one call per page: lead, infobox, sections, links, [^rN] references, conflicts. The References section
             is generated by code from the facts' locations, so a reference can never point to a source the page
             was not given.
  4. INDEX   index.md (catalogue, staff pages), restricted/index.md (HR), log.md (append-only, one line per source
             in ingest order: created/updated pages), manifest.json and facts.jsonl.

A batch build writes each page once from every fact any source gave it (fast and parallel); log.md replays which
pages each source touched. update() is the true incremental path: read the new source, then rewrite only the
pages it touches, starting from each page's current text.
"""
from __future__ import annotations

import datetime as _dt
import json
import pathlib
import re
import threading
import time
from collections import Counter, defaultdict
from concurrent.futures import ThreadPoolExecutor, as_completed

from . import wiki_sources as WS
from .wiki_llm import REASONING_LOW, WikiLLM, reply_usd

PKG = pathlib.Path(__file__).resolve().parents[2]
WIKI_DIR = PKG / "wiki_v4"
SCHEMA = (WIKI_DIR / "AGENTS.md").read_text() if (WIKI_DIR / "AGENTS.md").exists() else ""
TYPES = ["policy", "procedure", "manual", "release", "screen", "service-group", "error", "error-list", "supplier",
         "item-family", "person", "role", "cost-centre", "data-source", "topic", "decision", "answer"]
LINK = re.compile(r"\[\[([a-z0-9][a-z0-9-]*)(#[^\]|]*)?(?:\|([^\]]*))?\]\]")
REF = re.compile(r"\[\^(r\d+)\]")


def now() -> str:
    return _dt.datetime.now(_dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _json(text: str) -> dict:
    t = (text or "").strip()
    t = re.sub(r"^```(?:json)?\s*|\s*```$", "", t).strip()
    try:
        return json.loads(t)
    except json.JSONDecodeError:
        m = re.search(r"\{.*\}", t, re.S)
        if m:
            return json.loads(m.group(0))
        raise


def norm(s: str) -> str:
    s = str(s).replace("’", "'").replace("‘", "'").replace("“", '"').replace("”", '"')
    s = s.replace("–", "-").replace("—", "-").replace(" ", " ").replace("­", "")
    s = re.sub(r"\*\*|__|[•·▪]", "", s)
    return re.sub(r"\s+", "", s).lower()


# =================================================================================================== 1. READ
READ_SYSTEM = """You maintain the wiki of Northbridge Cycles (an e-bike maker in Manchester and Leeds that has run
Ledgerline ERP since 1998). You are ingesting its documentation dump one source at a time. The wiki's schema follows;
obey it exactly.

{schema}

REGISTRY: canonical page slugs that already exist or must be used for these entities (slug | type | title):
{registry}
"""

READ_USER = """SOURCE
{header}

PART {part} of {parts} ({loc})
-----
{text}
-----

Ingest this part. Decide which wiki pages it touches and give each page the facts this part contributes.

Rules
* The source's own page first (its document slug from the registry, or the data-source slug), then every entity or
  topic page it informs: suppliers, item families, people, roles, cost centres, screens, service groups, error codes,
  release changes, processes, rules and cross-document topics. Use registry slugs whenever the entity is in the
  registry; otherwise make a new slug that follows the schema's slug rules.
* A fact is one self-contained sentence with every code, number, date, name and condition exactly as written. Cover
  every rule, step, limit, field, code and decision in this part; skip boilerplate ("Who should install",
  generic tips) unless it states something specific to Northbridge or to Ledgerline's behaviour.
* "quote" is 5 to 25 words copied exactly from the text above (it is checked by code). "page" is the [p. N] the quote
  is on (null if the source has no pages); "section" is the nearest heading; for tables give "sheet" and "row" (the
  row key, e.g. VC-EIN-0042 or BAT-500@WH-MAN-STR).
* If the source status is superseded or future, say so in each fact ("In the superseded v4.0 ...", "From 1 Dec 2026
  ...").
* conflicts: where this source disagrees with, replaces, duplicates or overrides another document (name it by code
  or title), or where it is out of date, not yet in force, or a rule that exists only here (e-mail, meeting).
  kind is one of superseded, contradiction, future_dated, email_overrides_sop, near_duplicate, duplicate,
  rule_not_in_policy, legacy_terms, broken_links, inconsistent_naming.
* Facts from a source whose audience is hr go only on hr pages (its own document page).

Reply with JSON only:
{{"source_note": "2-3 sentences: what this source is, its date and status, what it is for",
  "pages": [{{"slug": "...", "type": "one of {types}", "title": "...",
             "facts": [{{"fact": "...", "quote": "...", "page": 3, "section": "...", "sheet": null, "row": null}}]}}],
  "conflicts": [{{"kind": "...", "other": "doc code or file", "detail": "one sentence"}}]}}"""


class Ingest:
    def __init__(self, root: str, out_dir: pathlib.Path, llm: WikiLLM, workers: int = 32, log=print):
        self.root, self.out, self.llm, self.workers, self.say = root, pathlib.Path(out_dir), llm, workers, log
        self.lock = threading.Lock()

    # ---------------------------------------------------------------- read one unit
    def read_unit(self, src: WS.Source, k: int, n: int, unit: WS.Unit, registry) -> dict:
        reg_txt = registry(unit.text) if callable(registry) else registry
        sys_ = READ_SYSTEM.format(schema=SCHEMA, registry=reg_txt)
        user = READ_USER.format(header=src.header(), part=k + 1, parts=n, loc=unit.loc, text=unit.text,
                                types=", ".join(TYPES))
        msgs = [{"role": "system", "content": sys_}, {"role": "user", "content": user}]
        t0 = time.perf_counter()
        r = self.llm.chat(msgs, response_format={"type": "json_object"}, **REASONING_LOW)
        calls = [r]
        try:
            out = _json(r.content)
        except Exception:
            msgs2 = msgs + [{"role": "assistant", "content": (r.content or "")[:20000]},
                            {"role": "user", "content": "That reply was not valid JSON (it may have been cut off). "
                                                        "Reply again with valid JSON only, at most 60 facts."}]
            r2 = self.llm.chat(msgs2, response_format={"type": "json_object"}, **REASONING_LOW)
            calls.append(r2)
            try:
                out = _json(r2.content)
            except Exception:
                out = {"source_note": "", "pages": [], "conflicts": [], "_error": "unparsed"}
        out["_stats"] = {"calls": len(calls), "tokens_in": sum(c.tokens_in for c in calls),
                         "tokens_out": sum(c.tokens_out for c in calls), "seconds": round(time.perf_counter() - t0, 2),
                         "llm_seconds": round(sum(c.seconds for c in calls), 2),
                         "usd": round(sum(reply_usd(c) for c in calls), 5), "replayed": all(c.replayed for c in calls)}
        out["_unit"] = {"loc": unit.loc, "k": k, "n": n}
        return out

    def read_all(self, srcs: list[WS.Source], registry, focus: set[str]) -> dict[str, list[dict]]:
        jobs = []
        for s in srcs:
            units = WS.ingest_units(s, focus)
            for k, u in enumerate(units):
                jobs.append((s, k, len(units), u))
        self.say(f"READ: {len(srcs)} sources, {len(jobs)} parts")
        res: dict[str, list[dict]] = defaultdict(list)
        done = 0
        with ThreadPoolExecutor(self.workers) as pool:
            futs = {pool.submit(self.read_unit, s, k, n, u, registry): (s, k) for s, k, n, u in jobs}
            for f in as_completed(futs):
                s, k = futs[f]
                try:
                    out = f.result()
                except Exception as e:  # a failed call is logged, not fatal
                    out = {"pages": [], "conflicts": [], "_error": repr(e)[:300], "_stats": {}, "_unit": {"k": k}}
                out["_finished"] = now()
                res[s.file].append(out)
                done += 1
                if done % 50 == 0:
                    self.say(f"  read {done}/{len(jobs)}  {self.llm.stats()}")
        for f in res:
            res[f].sort(key=lambda o: o["_unit"].get("k", 0))
        return res


# =================================================================================================== 2. MERGE
MERGE_PROMPT = """These are new wiki page slugs proposed while ingesting Northbridge's documents, with type, title and
how many facts each got. Several name the same topic in different words. Merge duplicates: map each duplicate slug to
the best slug of its group (prefer the clearest, most general name; never merge different error codes, screens,
suppliers or documents). Also map a slug to a registry slug when it is plainly the same thing.

REGISTRY SLUGS (fixed, may be targets): {registry}

NEW SLUGS:
{slugs}

Reply with JSON only: {{"merge": {{"duplicate-slug": "target-slug", ...}}}} (omit slugs that stay as they are)."""


def canonical(slug: str, reg: dict, people: dict, suppliers: dict, doc_slugs: list[str]) -> str:
    s = WS.slugify(slug or "")
    s = re.sub(r"^(error|err)-(err|w)-", r"\2-", s)
    s = re.sub(r"^error-", "err-", s)
    s = re.sub(r"^(screen-)+", "screen-", s)
    if s in reg:
        return s
    for d in doc_slugs:  # "pol-pur-001-purchase-policy" -> "pol-pur-001"
        if s.startswith(d + "-") or s == d.replace("-", ""):
            return d
    m = re.match(r"^(?:policy|procedure|manual|doc)-(.+)$", s)
    if m and m.group(1) in reg:
        return m.group(1)
    if s.startswith(("person-", "user-", "people-")):
        name = s.split("-", 1)[1]
        if name in people:
            return people[name]
    if s.startswith(("sup-", "supplier-")):
        name = s.split("-", 1)[1]
        if "sup-" + name in reg:
            return "sup-" + name
        for k, v in suppliers.items():
            if name == k or name.startswith(k + "-") or k.startswith(name):
                return v
    if s.startswith("cc-") or s.startswith("cost-centre-"):
        t = "cc-" + s.split("-", 2)[-1] if s.startswith("cost-centre-") else s
        if t in reg:
            return t
    m = re.match(r"^(?:screen-)?([a-z]{2,3}-[a-z]{2,4}-\d{2})(?:-.*)?$", s)
    if m and "screen-" + m.group(1) in reg:
        return "screen-" + m.group(1)
    m = re.match(r"^(err|w)-([a-z]{2,4})-(\d{3,4})(?:-.*)?$", s)
    if m:
        return f"{m.group(1)}-{m.group(2)}-{m.group(3)}"
    m = re.match(r"^rn-?(7-\d(?:-\d)?(?:-p\d)?)(?:-.*)?$", s)
    if m and "rn-" + m.group(1) in reg:
        return "rn-" + m.group(1)
    return s


def lookups(reg: dict):
    people, suppliers = {}, {}
    for slug, r in reg.items():
        if r["type"] == "person":
            nm = WS.slugify(r["title"].split(" (")[0])
            people[nm] = slug
            people[nm.split("-")[-1]] = people.get(nm.split("-")[-1], slug)
            people[slug.split("-", 1)[1]] = slug
        if r["type"] == "supplier":
            suppliers[WS.slugify(r["title"].split(" (")[0])] = slug
    doc_slugs = sorted([s for s, r in reg.items() if r["type"] in ("policy", "procedure", "manual", "release",
                                                                   "data-source")], key=len, reverse=True)
    return people, suppliers, doc_slugs


# =================================================================================================== 3. WRITE
WRITE_PROMPT = """You write one page of Northbridge Cycles' wiki, following the schema below.

{schema}

PAGE: {slug} (type {type}). Working title: {title}
Facts gathered from the raw sources (key, source, its date and status, location, fact):
{facts}

Pages you may link to (slug: title):
{links}

Write the page. Rules:
* Lead first (2-4 sentences, no heading): what this is and what matters about it today ({today}).
* Then the sections the schema requires for type {type}, then "## Versions and conflicts" only if the facts disagree,
  are superseded or are not yet in force (today's rule first, then the other, with dates and the kind), then
  "## See also". Do not write a References section: it is generated from your [^rN] keys.
* End every sentence that states a fact with its key(s) like [^r3] or [^r3][^r7]. Use only keys listed above. A fact
  marked superseded or future must never be written as today's rule.
* Link the first mention of every page in the list above with [[slug|text]] (or [[slug]]). Do not link to slugs that
  are not in the list.
* Plain, precise words; keep every code, number and date exactly as in the facts. No padding.

Reply in exactly this format:
SUMMARY: <one line of at most 25 words for the index>
INFOBOX:
<key>: <value>      (3 to 8 lines; omit the block's lines if the type has no infobox)
CONFLICTS:
- <kind> | <today's rule> | <older, other or future rule> | <keys, e.g. r2,r9>
(write "- none" if there are none)
BODY:
<the markdown page>"""


def _fact_line(k: str, f: dict) -> str:
    loc = f.get("loc_text", "")
    doc = f.get("doc") or f["file"]
    st = f.get("status", "current")
    date = f.get("date") or ""
    return f"[{k}] ({doc}; {date}; {st}; {loc}) {f['fact']}"


def loc_text(f: dict) -> str:
    bits = []
    if f.get("sheet"):
        bits.append(f"sheet {f['sheet']}")
    if f.get("row"):
        bits.append(f"row {f['row']}")
    if f.get("page"):
        bits.append(f"p. {f['page']}")
    if f.get("section"):
        sec = str(f["section"])
        bits.append(sec if sec.startswith("§") or not re.match(r"\d", sec) else "§" + sec)
    return ", ".join(bits) or "whole file"


def parse_written(text: str) -> dict:
    t = (text or "").strip()
    out = {"summary": "", "infobox": {}, "conflicts": [], "body": ""}
    m = re.search(r"^SUMMARY:\s*(.*)$", t, re.M)
    if m:
        out["summary"] = m.group(1).strip()
    m = re.search(r"^INFOBOX:\s*\n(.*?)^CONFLICTS:", t, re.M | re.S)
    if m:
        for line in m.group(1).splitlines():
            if ":" in line and line.strip() and not line.strip().startswith("("):
                k, v = line.split(":", 1)
                out["infobox"][k.strip(" -*")] = v.strip()
    m = re.search(r"^CONFLICTS:\s*\n(.*?)^BODY:", t, re.M | re.S)
    if m:
        for line in m.group(1).splitlines():
            line = line.strip()
            if line.startswith("-") and "|" in line:
                parts = [p.strip() for p in line[1:].split("|")]
                if len(parts) >= 3:
                    out["conflicts"].append({"kind": parts[0], "today": parts[1], "other": parts[2],
                                             "refs": re.findall(r"r\d+", parts[3]) if len(parts) > 3 else []})
    m = re.search(r"^BODY:\s*\n?(.*)$", t, re.M | re.S)
    out["body"] = (m.group(1) if m else t).strip()
    out["body"] = re.sub(r"^---\n.*?\n---\n", "", out["body"], flags=re.S).strip()  # the model sometimes adds front matter
    out["body"] = re.sub(r"\n#+\s*References\s*\n.*$", "", out["body"], flags=re.S).strip()
    return out


def render_page(slug: str, page: dict, refs: dict[str, dict]) -> str:
    """Front matter + infobox table + body + References (only keys the body uses, in order of first use)."""
    body = page["body"]
    used = []
    for k in REF.findall(body):
        if k in refs and k not in used:
            used.append(k)
    body = REF.sub(lambda m: m.group(0) if m.group(1) in refs else "", body)
    fm = {"title": page["title"], "type": page["type"], "slug": slug, "summary": page["summary"],
          "audience": page["audience"], "status": page["status"], "sources": page["sources"],
          "created": page.get("created", ""), "updated": page.get("updated", "")}
    lines = ["---"] + [f"{k}: {json.dumps(v, ensure_ascii=False)}" for k, v in fm.items()] + ["---", ""]
    if page.get("infobox"):
        lines += ["| | |", "|---|---|"] + [f"| {k} | {v} |" for k, v in page["infobox"].items()] + [""]
    lines += [body, "", "## References", ""]
    for k in used:
        f = refs[k]
        lines.append(f"[^{k}]: {f['file']}, {f.get('loc_text') or loc_text(f)}")
    return "\n".join(lines) + "\n"


def parse_page_file(text: str) -> tuple[dict, str]:
    fm = {}
    if text.startswith("---"):
        head, body = text[3:].split("\n---", 1)
        for line in head.strip().splitlines():
            if ":" in line:
                k, v = line.split(":", 1)
                try:
                    fm[k.strip()] = json.loads(v.strip())
                except json.JSONDecodeError:
                    fm[k.strip()] = v.strip()
        return fm, body.lstrip("\n")
    return fm, text


# =================================================================================================== the build
def _status_of(srcs_status: list[str]) -> str:
    s = set(srcs_status)
    if s <= {"superseded", "duplicate-file"}:
        return "superseded"
    if s == {"future"}:
        return "future"
    if s & {"superseded", "future"}:
        return "mixed"
    return "current"


def collect_facts(srcs_by: dict[str, WS.Source], reads: dict[str, list[dict]], reg: dict, ingest_order: list[str],
                  merge: dict | None = None, focus: set[str] | None = None):
    """Facts per canonical page, with quote verification and the permission rule applied."""
    people, suppliers, doc_slugs = lookups(reg)
    pages: dict[str, dict] = {}
    contributions: dict[str, list[str]] = {}
    dropped_perm = 0
    for file in ingest_order:
        src = srcs_by[file]
        page_texts = {u.page: norm(u.text) for u in src.units if u.page}
        full = norm(src.text) if not src.is_table else norm("\n".join(u.text for u in WS.ingest_units(src, focus or set())))
        touched = []
        for out in reads.get(file, []):
            for p in out.get("pages", []) or []:
                slug = canonical(p.get("slug", ""), reg, people, suppliers, doc_slugs)
                if merge:
                    slug = merge.get(slug, slug)
                if not slug:
                    continue
                if src.audience == "hr" and not (slug.startswith("hr-") or reg.get(slug, {}).get("audience") == "hr"
                                                 or (slug not in reg and slug.startswith(("topic-hr", "hr")))):
                    dropped_perm += len(p.get("facts", []) or [])
                    continue
                pg = pages.setdefault(slug, {"type": reg.get(slug, {}).get("type") or p.get("type") or "topic",
                                             "titles": Counter(), "facts": [], "sources": [], "audiences": set()})
                if slug in reg:
                    pg["titles"][reg[slug]["title"]] += 100
                pg["titles"][p.get("title") or slug] += 1
                for fct in p.get("facts", []) or []:
                    if not isinstance(fct, dict) or not fct.get("fact"):
                        continue
                    q = norm(fct.get("quote") or "")
                    page_no = fct.get("page") if isinstance(fct.get("page"), int) else None
                    if src.is_table:  # the quote must be in what the model was shown (profile + rows)
                        chunks = [norm(w) for w in re.split(r"[|=;]", fct.get("quote") or "") if len(norm(w)) > 2]
                        verified = bool(q) and (q in full or (bool(chunks) and all(c in full for c in chunks)))
                    else:
                        verified = bool(q) and (q in page_texts.get(page_no, "") or (page_no is None and q in full))
                        if not verified and q and q in full:
                            # right words, wrong page: fix the page number from the text
                            for pn, pt in page_texts.items():
                                if q in pt:
                                    fct["page"], page_no = pn, pn
                                    break
                            verified = "page-fixed" if page_no else True
                    f = {"file": file, "fact": fct["fact"].strip(), "quote": fct.get("quote"), "page": page_no,
                         "section": fct.get("section"), "sheet": fct.get("sheet"), "row": fct.get("row"),
                         "status": src.status, "date": src.date, "doc": (f"{src.doc_code} v{src.meta.get('version')}"
                                                                         if src.doc_code and src.meta.get("version")
                                                                         else src.doc_code),
                         "audience": src.audience, "verified": verified}
                    f["loc_text"] = loc_text(f)
                    pg["facts"].append(f)
                if file not in pg["sources"]:
                    pg["sources"].append(file)
                pg["audiences"].add(src.audience)
                if slug not in touched:
                    touched.append(slug)
        contributions[file] = touched
    return pages, contributions, dropped_perm


def link_candidates(slug: str, pages: dict, reg: dict, k: int = 45) -> list[str]:
    """Pages that share sources with this one, plus pages named by code in its facts."""
    mine = set(pages[slug]["sources"])
    co = Counter()
    for s, p in pages.items():
        if s != slug and p["_aud"] == pages[slug]["_aud"]:
            n = len(mine & set(p["sources"]))
            if n:
                co[s] = n + (2 if s in reg else 0)
    text = " ".join(f["fact"] for f in pages[slug]["facts"])
    named = set()
    for code in set(WS.CODEISH.findall(text)) | set(WS.DOC_CODE.findall(text)):
        for cand in (WS.doc_slug(code), "err-" + WS.slugify(code)[4:] if code.startswith("ERR-") else "",
                     WS.slugify(code), "screen-" + WS.slugify(code), "sup-" + WS.slugify(code), "cc-" + WS.slugify(code)):
            if cand and cand in pages and cand != slug:
                named.add(cand)
    out = list(named) + [s for s, _ in co.most_common(k) if s not in named]
    return out[:k + len(named)]


def select_facts(facts: list[dict], cap: int = 140, per_source: int = 30) -> list[dict]:
    seen, out, per = set(), [], Counter()
    order = {"current": 0, "email": 1, "meeting": 1, "future": 2, "duplicate-file": 3, "superseded": 3, "scan": 4}
    for f in sorted(facts, key=lambda f: (order.get(f["status"], 2), f["verified"] is False)):
        key = (f["file"], norm(f["fact"])[:120])
        if key in seen or per[f["file"]] >= per_source:
            continue
        seen.add(key)
        per[f["file"]] += 1
        out.append(f)
        if len(out) >= cap:
            break
    return out


class Builder(Ingest):
    def write_page(self, slug: str, pg: dict, pages: dict, reg: dict, current: str | None = None,
                   new_keys: list[str] | None = None) -> dict:
        facts = pg["_facts"]
        refs = {f"r{i + 1}": f for i, f in enumerate(facts)}
        links = link_candidates(slug, pages, reg)
        link_lines = "\n".join(f"{s}: {pages[s]['title']}" for s in links) or "(none)"
        title = pg["title"]
        prompt = WRITE_PROMPT.format(schema=SCHEMA, slug=slug, type=pg["type"], title=title,
                                     facts="\n".join(_fact_line(k, f) for k, f in refs.items()), links=link_lines,
                                     today=WS.TODAY)
        if current is not None:
            prompt += ("\n\nTHE PAGE AS IT STANDS (keep what is still true, keep its keys; work the new facts "
                       f"{', '.join(new_keys or [])} into it, and move anything they replace to Versions and conflicts):\n"
                       + current)
        t0 = time.perf_counter()
        r = self.llm.chat([{"role": "user", "content": prompt}], **REASONING_LOW)
        w = parse_written(r.content)
        if not w["body"]:
            w["body"] = "(page could not be written)"
        page = {"title": title, "type": pg["type"], "summary": w["summary"] or title, "infobox": w["infobox"],
                "body": w["body"], "conflicts": w["conflicts"], "audience": pg["_aud"], "status": pg["status"],
                "sources": pg["sources"]}
        page["links_out"] = sorted({m.group(1) for m in LINK.finditer(w["body"])})
        page["refs_used"] = sorted(set(REF.findall(w["body"])) & set(refs), key=lambda k: int(k[1:]))
        page["_stats"] = {"tokens_in": r.tokens_in, "tokens_out": r.tokens_out, "llm_seconds": r.seconds,
                          "seconds": round(time.perf_counter() - t0, 2), "usd": round(reply_usd(r), 5),
                          "replayed": r.replayed, "facts": len(facts), "links_offered": len(links)}
        page["_refs"] = refs
        return page

    def finalize_pages(self, pages: dict, reg: dict):
        for slug, pg in pages.items():
            pg["title"] = pg["titles"].most_common(1)[0][0] if pg["titles"] else slug
            pg["_aud"] = "hr" if pg["audiences"] == {"hr"} or reg.get(slug, {}).get("audience") == "hr" else "staff"
            pg["_facts"] = select_facts(pg["facts"])
            pg["status"] = _status_of([f["status"] for f in pg["_facts"]])
            if pg["type"] not in TYPES:
                pg["type"] = "topic"

    def write_all(self, pages: dict, reg: dict) -> dict:
        written = {}
        with ThreadPoolExecutor(self.workers) as pool:
            futs = {pool.submit(self.write_page, s, pg, pages, reg): s for s, pg in pages.items()}
            for i, f in enumerate(as_completed(futs)):
                s = futs[f]
                try:
                    written[s] = f.result()
                except Exception as e:
                    written[s] = {"_error": repr(e)[:300]}
                if (i + 1) % 50 == 0:
                    self.say(f"  wrote {i + 1}/{len(futs)}  {self.llm.stats()}")
        return written

    def merge_topics(self, pages: dict, reg: dict) -> tuple[dict, dict]:
        new = {s: p for s, p in pages.items() if s not in reg}
        if not new:
            return {}, {}
        lines = "\n".join(f"{s} | {p['type']} | {p['titles'].most_common(1)[0][0]} | {len(p['facts'])} facts"
                          for s, p in sorted(new.items()))
        regs = ", ".join(s for s, r in reg.items() if r["type"] in ("policy", "procedure", "manual", "data-source",
                                                                    "release", "supplier", "item-family"))
        r = self.llm.chat([{"role": "user", "content": MERGE_PROMPT.format(registry=regs, slugs=lines)}],
                          response_format={"type": "json_object"}, **REASONING_LOW)
        try:
            m = _json(r.content).get("merge", {})
        except Exception:
            m = {}
        ok = {}
        for a, b in m.items():
            a, b = WS.slugify(a), WS.slugify(b)
            if a in new and a != b and (b in pages or b in reg) and not re.match(r"^(err|w|screen|sup|cc)-", a):
                ok[a] = b
        # resolve chains a->b->c
        for a in list(ok):
            seen = {a}
            while ok[a] in ok and ok[a] not in seen:
                seen.add(ok[a])
                ok[a] = ok[ok[a]]
        return ok, {"tokens_in": r.tokens_in, "tokens_out": r.tokens_out, "llm_seconds": r.seconds,
                    "usd": round(reply_usd(r), 5), "proposed": len(m), "accepted": len(ok)}

    def save(self, written: dict, pages: dict, contributions: dict, ingest_order: list[str], reads: dict,
             srcs_by: dict, report: dict, log_lines: list[str] | None = None):
        out = self.out
        (out / "pages").mkdir(parents=True, exist_ok=True)
        (out / "restricted").mkdir(parents=True, exist_ok=True)
        today = now()[:10]
        manifest = {"built": now(), "dump_files": len(srcs_by), "pages": {}}
        for slug, w in sorted(written.items()):
            if "_error" in w:
                continue
            w.setdefault("created", today)
            w["updated"] = today
            sub = "restricted" if w["audience"] == "hr" else "pages"
            (out / sub / f"{slug}.md").write_text(render_page(slug, w, w["_refs"]))
            manifest["pages"][slug] = {k: w[k] for k in ("title", "type", "summary", "audience", "status", "sources",
                                                         "links_out", "refs_used", "conflicts", "infobox")}
            manifest["pages"][slug]["path"] = f"{sub}/{slug}.md"
            manifest["pages"][slug]["stats"] = w["_stats"]
            manifest["pages"][slug]["refs"] = {k: {kk: w["_refs"][k].get(kk) for kk in
                                                   ("file", "page", "section", "sheet", "row", "loc_text", "quote",
                                                    "verified", "status", "date")}
                                               for k in w["refs_used"]}
        write_index(out, manifest)
        # log.md: one line per source in ingest order, created vs updated by that order
        seen = set()
        lines = ["# log.md", "", "Append-only. One line per operation, oldest first. "
                 "`ingest | file | +created ~updated | pages`.", ""]
        if log_lines:
            lines = log_lines
        for file in ingest_order:
            touched = [s for s in contributions.get(file, []) if s in manifest["pages"]]
            created = [s for s in touched if s not in seen]
            seen |= set(touched)
            ts = max((o.get("_finished", "") for o in reads.get(file, [])), default=now())
            lines.append(f"## [{ts}] ingest | {file} | +{len(created)} ~{len(touched) - len(created)} | "
                         + ", ".join(touched))
        lines.append(f"## [{now()}] build | {len(manifest['pages'])} pages | index.md rebuilt")
        (out / "log.md").write_text("\n".join(lines) + "\n")
        (out / "manifest.json").write_text(json.dumps(manifest, indent=1, ensure_ascii=False))
        with (out / "facts.jsonl").open("w") as fh:
            for slug, pg in pages.items():
                for f in pg["facts"]:
                    fh.write(json.dumps({"slug": slug, **{k: v for k, v in f.items()}}, ensure_ascii=False) + "\n")
        with (out / "sources.jsonl").open("w") as fh:
            for file in ingest_order:
                s = srcs_by[file]
                rd = reads.get(file, [])
                fh.write(json.dumps({"file": file, "fmt": s.fmt, "status": s.status, "audience": s.audience,
                                     "doc": s.doc_code, "version": s.meta.get("version"),
                                     "effective": s.meta.get("effective"), "date": s.date,
                                     "note": " ".join(o.get("source_note", "") for o in rd if o.get("source_note")),
                                     "conflicts": [c for o in rd for c in (o.get("conflicts") or [])],
                                     "pages": contributions.get(file, []), "parts": len(rd),
                                     "stats": {k: sum((o.get("_stats") or {}).get(k, 0) for o in rd)
                                               for k in ("calls", "tokens_in", "tokens_out", "usd", "llm_seconds")},
                                     "errors": [o["_error"] for o in rd if o.get("_error")]},
                                    ensure_ascii=False) + "\n")
        return manifest


TYPE_TITLES = [("policy", "Policies and amendments"), ("procedure", "Procedures (SOPs)"), ("decision", "Decisions"),
               ("topic", "Topics"), ("manual", "Manuals and references"), ("release", "Releases and patches"),
               ("screen", "Screens"), ("service-group", "Service groups"), ("error", "Error and warning codes"),
               ("error-list", "Error lists"), ("supplier", "Suppliers"), ("item-family", "Item families"),
               ("person", "People"), ("role", "Roles"), ("cost-centre", "Cost centres"),
               ("data-source", "Data sources (structured files)"), ("answer", "Filed answers")]


def write_index(out: pathlib.Path, manifest: dict):
    for aud, path, head in (("staff", out / "index.md", "Northbridge wiki: index"),
                            ("hr", out / "restricted" / "index.md", "Northbridge wiki: restricted (HR only) index")):
        pages = {s: p for s, p in manifest["pages"].items() if p["audience"] == aud}
        lines = [f"# {head}", "", f"{len(pages)} pages. Read this first; open a page with its slug. "
                 "Format: `[[slug]] Title: summary`.", ""]
        for t, name in TYPE_TITLES:
            group = sorted((s, p) for s, p in pages.items() if p["type"] == t)
            if not group:
                continue
            lines += [f"## {name} ({len(group)})", ""]
            for s, p in group:
                flag = {"superseded": " [superseded]", "future": " [not yet in force]"}.get(p.get("status"), "")
                lines.append(f"- [[{s}]] {p['title']}: {p['summary']}{flag}")
            lines.append("")
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("\n".join(lines))


INGEST_FOLDER_ORDER = ["(root)", "05_master_data", "07_data_dictionary", "01_policies", "02_procedures",
                       "03_ledgerline_manuals", "04_service_definitions", "08_release_notes", "11_training",
                       "12_integrations", "10_meeting_notes", "09_email_archive", "06_transactions", "99_scans"]


def ingest_order(srcs: list[WS.Source]) -> list[str]:
    """Reference data first (so the namespace exists), then policies -> procedures -> manuals -> services -> releases
    -> training -> integrations -> meetings -> e-mails (by date) -> extracts -> scans."""
    rank = {f: i for i, f in enumerate(INGEST_FOLDER_ORDER)}
    return [s.file for s in sorted(srcs, key=lambda s: (rank.get(s.folder, 50), s.date if s.fmt == "eml" else "",
                                                        s.file))]


def build(root: str, out_dir, llm: WikiLLM, workers: int = 32, files: list[str] | None = None, log=print) -> dict:
    t_all = time.perf_counter()
    b = Builder(root, out_dir, llm, workers, log)
    t0 = time.perf_counter()
    srcs = WS.load_sources(root, files)
    srcs_by = {s.file: s for s in srcs}
    all_srcs = srcs if files is None else WS.load_sources(root)
    reg = WS.build_registry(all_srcs)
    focus = WS.focus_codes(all_srcs)
    t_parse = time.perf_counter() - t0
    keys = WS.registry_keys(reg)
    registry = lambda text: WS.registry_for(text, reg, keys)  # noqa: E731
    log(f"parsed {len(srcs)} sources in {t_parse:.1f}s; registry {len(reg)} slugs")
    order = ingest_order(srcs)
    t0 = time.perf_counter()
    reads = b.read_all(srcs, registry, focus)
    t_read = time.perf_counter() - t0
    s_read = llm.stats()
    log(f"READ done in {t_read:.0f}s {s_read}")
    pages, contributions, dropped = collect_facts(srcs_by, reads, reg, order, focus=focus)
    t0 = time.perf_counter()
    merge, merge_stats = b.merge_topics(pages, reg)
    pages, contributions, dropped = collect_facts(srcs_by, reads, reg, order, merge, focus=focus)
    t_merge = time.perf_counter() - t0
    b.finalize_pages(pages, reg)
    n0 = len(llm.log)
    t0 = time.perf_counter()
    written = b.write_all(pages, reg)
    t_write = time.perf_counter() - t0
    s_write = llm.stats(n0)
    log(f"WRITE done in {t_write:.0f}s {s_write}")
    report = {"started": now(), "sources": len(srcs), "parts": sum(len(v) for v in reads.values()),
              "registry_slugs": len(reg), "merge": merge_stats, "merge_map": merge,
              "facts_dropped_permission": dropped}
    manifest = b.save(written, pages, contributions, order, reads, srcs_by, report)
    report.update(stats(manifest, pages, reads, b.out))
    report["seconds"] = {"parse": round(t_parse, 1), "read": round(t_read, 1), "merge": round(t_merge, 1),
                         "write": round(t_write, 1), "total": round(time.perf_counter() - t_all, 1)}
    report["llm"] = {"read": s_read, "write": s_write, "all": llm.stats()}
    return report


def stats(manifest: dict, pages: dict, reads: dict, out: pathlib.Path) -> dict:
    mp = manifest["pages"]
    inbound = Counter(l for p in mp.values() for l in p["links_out"] if l in mp)
    all_links = [l for p in mp.values() for l in p["links_out"]]
    facts = [f for pg in pages.values() for f in pg["facts"]]
    words = sum(len((out / p["path"]).read_text().split()) for p in mp.values())
    return {"pages": len(mp), "pages_by_type": dict(Counter(p["type"] for p in mp.values())),
            "pages_by_audience": dict(Counter(p["audience"] for p in mp.values())),
            "links": len(all_links), "links_resolved": sum(1 for l in all_links if l in mp),
            "orphans": sorted(s for s in mp if inbound[s] == 0),
            "references": sum(len(p["refs_used"]) for p in mp.values()),
            "facts": len(facts), "facts_quote_verified": sum(1 for f in facts if f["verified"]),
            "facts_page_fixed": sum(1 for f in facts if f["verified"] == "page-fixed"),
            "wiki_words": words, "read_errors": sum(1 for v in reads.values() for o in v if o.get("_error"))}


# =================================================================================================== update (incremental)
def _pages_from_disk(out: pathlib.Path, man: dict) -> dict:
    facts = defaultdict(list)
    fp = out / "facts.jsonl"
    if fp.exists():
        for line in fp.open():
            f = json.loads(line)
            facts[f.pop("slug")].append(f)
    pages = {}
    for slug, p in man["pages"].items():
        fs = facts.get(slug, [])
        pages[slug] = {"type": p["type"], "titles": Counter({p["title"]: 1000}), "facts": fs,
                       "sources": list(p["sources"]), "audiences": {p["audience"]}, "title": p["title"],
                       "_aud": p["audience"], "status": p.get("status", "current")}
    return pages


def update(new_files: list[str], root: str, out_dir, llm: WikiLLM, workers: int = 16, log=print) -> dict:
    """Absorb new source(s) into an existing wiki, Karpathy-style: read the source, then rewrite only the pages it
    touches (each from its current text plus the new facts), create the pages it needs, rebuild the index, log it."""
    t_all = time.perf_counter()
    out = pathlib.Path(out_dir)
    man = json.loads((out / "manifest.json").read_text())
    b = Builder(root, out, llm, workers, log)
    n0 = len(llm.log)
    srcs = WS.load_sources(root, new_files)
    srcs_by = {s.file: s for s in srcs}
    # the registry is now the wiki itself: every page that exists, plus the entities named in the new text
    reg = {s: {"type": p["type"], "title": p["title"], "audience": p["audience"]} for s, p in man["pages"].items()}
    keys = WS.registry_keys(reg)
    registry = lambda text: WS.registry_for(text, reg, keys)  # noqa: E731
    t0 = time.perf_counter()
    reads = b.read_all(srcs, registry, set())
    t_read = time.perf_counter() - t0
    order = [s.file for s in srcs]
    new_pages, contributions, _ = collect_facts(srcs_by, reads, reg, order)
    pages = _pages_from_disk(out, man)
    for s, pg in pages.items():
        pg["_facts"] = select_facts(pg["facts"])
    touched, created = [], []
    for slug, npg in new_pages.items():
        if slug in pages:
            pg = pages[slug]
            old_n = len(pg["_facts"])
            pg["facts"] += npg["facts"]
            pg["_facts"] = pg["_facts"] + [f for f in npg["facts"]]
            pg["sources"] += [f for f in npg["sources"] if f not in pg["sources"]]
            pg["status"] = _status_of([f["status"] for f in pg["_facts"]])
            pg["_new_keys"] = [f"r{i + 1}" for i in range(old_n, len(pg["_facts"]))]
            touched.append(slug)
        else:
            npg["title"] = npg["titles"].most_common(1)[0][0]
            npg["_aud"] = "hr" if npg["audiences"] == {"hr"} else "staff"
            npg["_facts"] = select_facts(npg["facts"])
            npg["status"] = _status_of([f["status"] for f in npg["_facts"]])
            npg["type"] = npg["type"] if npg["type"] in TYPES else "topic"
            pages[slug] = npg
            created.append(slug)
    t0 = time.perf_counter()
    written = {}

    def one(slug):
        pg = pages[slug]
        cur = None
        if slug in man["pages"]:
            cur = (out / man["pages"][slug]["path"]).read_text()
        return slug, b.write_page(slug, pg, pages, reg, current=cur, new_keys=pg.get("_new_keys"))

    with ThreadPoolExecutor(workers) as pool:
        for slug, w in pool.map(one, touched + created):
            written[slug] = w
    t_write = time.perf_counter() - t0
    today = now()[:10]
    for slug, w in written.items():
        w["created"] = man["pages"].get(slug, {}).get("created", today) if slug in man["pages"] else today
        w["updated"] = today
        sub = "restricted" if w["audience"] == "hr" else "pages"
        (out / sub / f"{slug}.md").write_text(render_page(slug, w, w["_refs"]))
        man["pages"][slug] = {k: w[k] for k in ("title", "type", "summary", "audience", "status", "sources",
                                                "links_out", "refs_used", "conflicts", "infobox")}
        man["pages"][slug].update(path=f"{sub}/{slug}.md", stats=w["_stats"],
                                  refs={k: {kk: w["_refs"][k].get(kk) for kk in ("file", "page", "section", "sheet",
                                                                                 "row", "loc_text", "quote",
                                                                                 "verified", "status", "date")}
                                        for k in w["refs_used"]})
    man.setdefault("updates", []).append({"at": now(), "files": new_files, "touched": touched, "created": created})
    (out / "manifest.json").write_text(json.dumps(man, indent=1, ensure_ascii=False))
    write_index(out, man)
    with (out / "facts.jsonl").open("a") as fh:
        for slug, npg in new_pages.items():
            for f in npg["facts"]:
                fh.write(json.dumps({"slug": slug, **f}, ensure_ascii=False) + "\n")
    with (out / "log.md").open("a") as fh:
        for file in order:
            ts = max((o.get("_finished", "") for o in reads.get(file, [])), default=now())
            fh.write(f"## [{ts}] ingest | {file} | +{len(created)} ~{len(touched)} | "
                     + ", ".join(contributions.get(file, [])) + "\n")
    st = llm.stats(n0)
    return {"files": new_files, "pages_touched": len(touched) + len(created), "updated": touched, "created": created,
            "seconds": {"read": round(t_read, 1), "write": round(t_write, 1), "total": round(time.perf_counter() - t_all, 1)},
            "llm": st, "usd": st["usd"], "facts_added": sum(len(p["facts"]) for p in new_pages.values()),
            "page_stats": {s: w["_stats"] for s, w in written.items()}}
