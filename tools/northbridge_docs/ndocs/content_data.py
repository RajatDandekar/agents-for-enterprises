# ------------------------------------------------------------------------------------------------ services
def _y(v):
    s = str(v)
    if s == "" or re.search(r"[:#{}\[\],&*!|>'\"%@`]", s) or s.lower() in ("yes", "no", "true", "false", "null", "on", "off") or re.fullmatch(r"[\d.]+", s):
        return '"' + s.replace('"', '\\"') + '"'
    return s


def svc_yaml(s):
    lines = [f"# Ledgerline ERP 7.2 service definition, exported from the service registry on 26-10-2026 by JFLETCHER.",
             f"service: {s['name']}", f"title: {_y(s['title'])}", f"module: {s['module']}", f"kind: {s['kind']}",
             f"screen: {s['screen'] or 'null'}", f"since: {_y(s['since'])}",
             f"endpoint: POST /ll72/svc/{s['name']}", "auth: session token in header X-LL-Session; the user's role must allow the service",
             "request:", "  fields:"]
    if not s["fields"]:
        lines[-1] = "  fields: []"
    for f in s["fields"]:
        lines.append(f"  - {{name: {f['name']}, type: {f['type']}, required: {'true' if f['required'] else 'false'}, desc: {_y(f['desc'])}}}")
    lines += ["response:", "  envelope: {rc: \"S | W | E\", err_cd: \"error code when rc is E\", msg: \"short message in capitals\", data: \"result\"}"]
    lines.append("errors:" if s["errors"] else "errors: []")
    for e in s["errors"]:
        lines.append(f"  - {{code: {e['code']}, msg: {_y(e['msg'])}}}")
    lines.append("warnings: [" + ", ".join(s["warnings"]) + "]")
    lines.append("common_errors:")
    for code, msg in COMMON:
        lines.append(f"  - {{code: {code}, msg: {_y(msg)}}}")
    lines.append("procedures: [" + ", ".join(s["procedures"]) + "]")
    if s["name"] in SVC_NOTES:
        lines.append(f"notes: {_y(SVC_NOTES[s['name']])}")
    return "\n".join(lines) + "\n"


def svc_xml(s):
    ns = s["module"].lower()
    el = []
    for f in s["fields"]:
        t = {"str": "xs:string", "int": "xs:integer", "float": "xs:decimal", "date": "xs:date"}[f["type"]]
        el.append(f'          <xs:element name="{f["name"]}" type="{t}" minOccurs="{1 if f["required"] else 0}">'
                  f'<xs:annotation><xs:documentation>{f["desc"]}</xs:documentation></xs:annotation></xs:element>')
    errs = "\n".join(f'    <ll:error code="{e["code"]}" msg="{e["msg"].replace("<", "&lt;").replace(">", "&gt;")}"/>' for e in s["errors"])
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- Ledgerline {s['since']} SOAP gateway service, still served by Ledgerline 7.2 through the compatibility listener on port 8091. -->
<!-- Do not edit: regenerated by the gateway on deploy. Last export 2016-11-03 (DRAMSDEN left 2012; owner now IT, JFLETCHER). -->
<wsdl:definitions name="{s['name']}" targetNamespace="urn:ledgerline:svc:{ns}"
    xmlns:wsdl="http://schemas.xmlsoap.org/wsdl/" xmlns:xs="http://www.w3.org/2001/XMLSchema"
    xmlns:soap="http://schemas.xmlsoap.org/wsdl/soap/" xmlns:ll="urn:ledgerline:meta" xmlns:tns="urn:ledgerline:svc:{ns}">
  <wsdl:documentation>{s['title']}. Module {s['module']}. Kind {s['kind']}. Screen {s['screen'] or 'none'}.</wsdl:documentation>
  <wsdl:types>
    <xs:schema targetNamespace="urn:ledgerline:svc:{ns}">
      <xs:element name="{s['name']}Request">
        <xs:complexType>
          <xs:sequence>
{chr(10).join(el)}
          </xs:sequence>
        </xs:complexType>
      </xs:element>
      <xs:element name="{s['name']}Response">
        <xs:complexType><xs:sequence>
          <xs:element name="rc" type="xs:string"/><xs:element name="err_cd" type="xs:string" minOccurs="0"/>
          <xs:element name="msg" type="xs:string"/><xs:element name="data" type="xs:anyType" minOccurs="0"/>
        </xs:sequence></xs:complexType>
      </xs:element>
    </xs:schema>
  </wsdl:types>
  <wsdl:message name="{s['name']}In"><wsdl:part name="body" element="tns:{s['name']}Request"/></wsdl:message>
  <wsdl:message name="{s['name']}Out"><wsdl:part name="body" element="tns:{s['name']}Response"/></wsdl:message>
  <wsdl:portType name="{s['name']}Port">
    <wsdl:operation name="{s['name']}"><wsdl:input message="tns:{s['name']}In"/><wsdl:output message="tns:{s['name']}Out"/></wsdl:operation>
  </wsdl:portType>
  <wsdl:binding name="{s['name']}Binding" type="tns:{s['name']}Port">
    <soap:binding style="document" transport="http://schemas.xmlsoap.org/soap/http"/>
    <wsdl:operation name="{s['name']}"><soap:operation soapAction="urn:ledgerline:{s['name']}"/></wsdl:operation>
  </wsdl:binding>
  <wsdl:service name="{s['name']}Service">
    <wsdl:port name="{s['name']}Port" binding="tns:{s['name']}Binding"><soap:address location="http://ll72-app01:8091/ws/{ns}/{s['name']}"/></wsdl:port>
  </wsdl:service>
  <ll:errors>
{errs}
  </ll:errors>
</wsdl:definitions>
"""


def services(c):
    base = "04_service_definitions"
    rows = []
    for s in c.cat.services:
        ext = "xml" if s["fmt"] == "xml" else "yaml"
        path = f"{base}/{s['folder']}/{s['name']}.{ext}"
        d = Doc(path, s["name"])
        d.raw = svc_xml(s) if ext == "xml" else svc_yaml(s)
        c.add(d)
        rows.append([s["name"], s["module"], s["title"], s["kind"], s["screen"] or "", f"{s['folder']}/{s['name']}.{ext}", s["since"],
                     "yes" if s["real"] else "no"])
        if s["real"]:
            req = [f["name"] for f in s["fields"] if f["required"]]
            d.fact(f"F-SVC-{s['name']}", f"Service {s['name']} ({s['title']}): fields {', '.join(f['name'] for f in s['fields']) or 'none'}; required {', '.join(req) or 'none'}; screen {s['screen']}.",
                   [f"service: {s['name']}"] + [f"{{name: {f['name']}, type: {f['type']}, required: {'true' if f['required'] else 'false'}" for f in s["fields"]],
                   section="request.fields")
            for e in s["errors"]:
                if s["name"] in ("po_save", "sup_create", "grn_save", "po_release", "pr_submit", "po_approve", "sup_cert_upload", "po_amend"):
                    d.fact(f"F-SVCERR-{s['name']}-{e['code']}", f"Service {s['name']} can return {e['code']} {e['msg']}.",
                           [f"code: {e['code']}, msg: {_y(e['msg'])}"], section="errors")
            if s["name"] in SVC_NOTES:
                d.fact(f"F-SVCNOTE-{s['name']}", f"Service {s['name']} note: {SVC_NOTES[s['name']]}", [SVC_NOTES[s["name"]][:90]], section="notes")
    rows.sort()
    idx = Book(f"{base}/service_index.csv", [Sheet("index", ["service", "module", "title", "kind", "screen", "file", "since", "in_sandbox_lecture_2"], rows)])
    c.add(idx)
    rd = Doc(f"{base}/README.md", "Ledgerline 7.2 service definitions")
    rd.p("One file per service, exported from Ledgerline's service registry (SYS-SVC) on 26 October 2026. YAML for services defined in "
         "Ledgerline 7; WSDL-style XML for the old SOAP gateway services (EDI, bank payments, carrier booking), which still run through the "
         "compatibility listener.")
    rd.table(["Folder", "Module", "Services"], [[f, m, str(sum(1 for s in c.cat.services if s['folder'] == f))] for m, f in
                                               [("PUR", "purchase"), ("INV", "inventory"), ("AP", "accounts_payable"), ("SAL", "sales"), ("PRD", "production"), ("ADM", "admin")]])
    rd.p("Every service takes a flat payload (at most 12 fields) and answers in the legacy envelope {rc, err_cd, msg, data}. rc is S "
         "(success), W (success with a warning) or E (error). Field names are the legacy column names; see 07_data_dictionary.")
    rd.p("The purchase/ folder holds the 38 services of the purchasing module, the same 38 the integration account SVC_AGENT can call. "
         "_legacy_6x/ holds three Ledgerline 6 definitions kept 'for reference' after the 2015 upgrade. They no longer exist on the server.")
    c.add(rd)
    rd.fact("F-SVC-38", "04_service_definitions/purchase holds the 38 purchasing-module services.", ["The purchase/ folder holds the 38 services of the purchasing module"])
    for name, old_fields in [("PO_ENTRY_SAVE", ["VENDOR_NO", "ITEM_NO", "QTY", "PRICE", "TAX_REGION", "CC", "DUE_DATE"]),
                             ("VENDOR_ADD", ["VENDOR_NAME", "TOWN", "COUNTY", "VAT_REG", "TERMS"]),
                             ("REQ_ENTRY", ["ITEM_NO", "QTY", "CC", "DUE_DATE", "REQUESTER"])]:
        d = Doc(f"{base}/_legacy_6x/{name}.xml", name)
        flds = "\n".join(f'    <field name="{f}" type="CHAR" />' for f in old_fields)
        d.raw = (f'<?xml version="1.0" encoding="ISO-8859-1"?>\n<!-- Ledgerline 6.4 RPC definition. Superseded by Ledgerline 7.0 (2015). Kept for reference. -->\n'
                 f'<rpc name="{name}" version="6.4" transport="LL6-RPC">\n  <input>\n{flds}\n  </input>\n  <output><field name="RETCODE"/><field name="DOCNO"/></output>\n</rpc>\n')
        c.add(d)
    c.mess("superseded", [f"{base}/_legacy_6x/PO_ENTRY_SAVE.xml", f"{base}/purchase/po_save.yaml"],
           "Three Ledgerline 6 RPC definitions (PO_ENTRY_SAVE, VENDOR_ADD, REQ_ENTRY) remain next to the 7.2 services, with old field names (VENDOR_NO, TAX_REGION). They no longer exist on the server.")
    c.mess("mixed_formats", [f"{base}/sales/edi_ord_in.xml", f"{base}/purchase/po_save.yaml"],
           "Service definitions come in two formats: YAML (7.x services) and WSDL-style XML (21 old SOAP gateway services: EDI, payments, bank details, carrier).")


