def _tables():
    out = []
    for sql, mod in [(S.SCHEMA, "PUR/core"), (R.SCHEMA, "INV")]:
        for m in re.finditer(r"CREATE TABLE (?:IF NOT EXISTS )?(\w+)\((.*?)\);", sql, re.S):
            cols = []
            for part in [p.strip() for p in m.group(2).replace("\n", " ").split(",") if p.strip()]:
                bits = part.split()
                cols.append((bits[0], bits[1] if len(bits) > 1 else "TEXT", "PK" if "PRIMARY" in part else ""))
            out.append((m.group(1), mod, cols))
    for mod, (folder, mtitle, ents) in GEN.items():
        for ent, code, title, screen, key, fspec, ops in ents:
            cols = [(key, "TEXT", "PK")] if key else []
            for part in [p for p in fspec.split("|") if p]:
                n, t = part.split(":")[:2]
                if n != key:
                    cols.append((n, {"str": "TEXT", "int": "INT", "float": "REAL", "date": "TEXT"}[t.rstrip("!") or "str"], ""))
            cols += [("status", "TEXT", ""), ("created_by", "TEXT", ""), ("created_on", "TEXT", "")]
            out.append((f"{ent}_hdr", mod, cols))
    return out


