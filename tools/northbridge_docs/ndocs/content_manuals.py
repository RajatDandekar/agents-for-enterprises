def service_reference(c):
    """The vendor's printed service reference: every service in the registry, one section each (duplicates 04_service_definitions)."""
    from .catalog import COMMON
    d = Doc(f"{P}/MAN-SVC-72 Service Reference (all modules) v7.2.3.pdf", "Ledgerline ERP 7.2 Service Reference", doc_id="MAN-SVC-72", version="7.2.3",
            effective="2025-01-15", owner="Ledgerline Systems, Integration Group", style="manual", company=VENDOR, toc=True)
    d.h(1, "1. Calling a service")
    d.p("Every service is an HTTP POST to /ll72/svc/<service> with a flat JSON payload of at most 12 fields and the session token in header "
        "X-LL-Session. The answer is the legacy envelope {rc, err_cd, msg, data}: rc is S (success), W (success with a warning) or E (error). "
        "Unknown fields are refused with ERR-SYS-0422; missing mandatory fields with ERR-SYS-0421; a role that does not allow the service gets ERR-SEC-0001.")
    d.table(["Code", "Message (every service)"], [list(x) for x in COMMON])
    mods = [("PUR", "Purchase"), ("INV", "Inventory"), ("AP", "Accounts payable"), ("SAL", "Sales"), ("PRD", "Production"), ("ADM", "Administration")]
    for i, (m, title) in enumerate(mods, 2):
        d.h(1, f"{i}. {title} services")
        for s in [x for x in c.cat.services if x["module"] == m]:
            d.h(2, f"{s['name']}  {s['title']}")
            d.p(f"Kind: {s['kind']}. Screen: {s['screen'] or 'none'}. Since: {s['since']}. Procedures: {', '.join(s['procedures']) or 'none'}.", "small")
            if s["fields"]:
                d.table(["Field", "Type", "Mandatory", "Description"], [[f["name"], f["type"], "Yes" if f["required"] else "No", f["desc"]] for f in s["fields"]],
                        widths=[1.4, 0.7, 0.9, 2.6])
            if s["errors"] or s["warnings"]:
                d.table(["Code", "Message"], [[e["code"], e["msg"]] for e in s["errors"]] + [[w, c.cat.errors.get(w, {}).get("msg", "")] for w in s["warnings"]], widths=[1.3, 4])
    c.add(d)
    d.fact("F-SVCREF-PO", "Service reference: po_save PO SAVE on PUR-PO-01, with ERR-PO-0412 among its errors.", ["po_save PO SAVE", "Screen: PUR-PO-01"], section="po_save")
    c.mess("duplicate", [d.path, "04_service_definitions/purchase/po_save.yaml"], "Every service is described twice: once in its own YAML/XML file and again in the printed service reference PDF.")
