# ------------------------------------------------------------------------------------------------ screens
def screen_catalogue(c):
    import yaml

    screens = {}
    for fn in sorted(os.listdir(SCREENS_DIR)):
        if not fn.endswith(".yaml"):
            continue
        raw = open(os.path.join(SCREENS_DIR, fn), encoding="utf-8").read()
        for a, b in YAML_FIX:
            raw = raw.replace(a, b)
        y = yaml.safe_load(raw)
        y["real"] = True
        screens[y["code"]] = y
    for s in c.cat.services:
        sc = s.get("screen")
        if not sc:
            continue
        if sc not in screens:
            screens[sc] = dict(code=sc, title=_screen_title(c, s), menu=_menu(s), roles=ROLES.get(s["module"], "[PUR-EXEC, PUR-SR, SYS-ADMIN]"),
                               help="", fields=[], tasks=[], state=[], real=False, module=s["module"])
        sco = screens[sc]
        if sco.get("real"):
            continue
        for f in s["fields"]:
            if f["name"] not in [x["name"] for x in sco["fields"]]:
                sco["fields"].append(dict(name=f["name"], label=f["desc"], type=f["type"], req=f["required"]))
        sco["tasks"].append(dict(button=s["op"].replace("_", " ").title() if "op" in s else s["title"].title(), service=s["name"],
                                 key=KEYS.get(s.get("op", ""), "")))
        for e in s["errors"]:
            if e["code"] not in [x.get("error") for x in sco["state"]]:
                sco["state"].append(dict(rule=e["msg"].title(), error=e["code"]))
    if "PUR-SUP-03" not in screens:
        screens["PUR-SUP-03"] = dict(code="PUR-SUP-03", title="SUPPLIER ENQUIRY", menu="Masters > Supplier enquiry", roles="[ALL]",
                                     help="Search suppliers by any part of the name. Always search before creating a supplier.",
                                     fields=[dict(name="q", label="NAME LIKE", type="str", req=True)],
                                     tasks=[dict(button="Find", service="sup_search", key="Enter")], state=[], real=False, module="PUR")
    return dict(sorted(screens.items()))


def _screen_title(c, s):
    return re.sub(r" (SAVE|GET|LIST|POST|CANCEL|APPROVE|RELEASE|CREATE|FETCH|RUN|QUERY|PROPOSE)$", "", s["title"]) + (" ENTRY" if s.get("op") == "save" else "")


def _menu(s):
    m = {"INV": "Inventory", "AP": "Accounts payable", "SAL": "Sales", "PRD": "Production", "ADM": "System", "PUR": "Purchase"}[s["module"]]
    return f"{m} > {s['title'].split(' ')[0].title()} {s['title'].split(' ')[1].lower() if len(s['title'].split(' ')) > 2 else ''}".strip()


