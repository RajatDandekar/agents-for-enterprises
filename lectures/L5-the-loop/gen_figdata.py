def load(name):
    p = LOGS / name
    return json.loads(p.read_text()) if p.exists() else None


def short(v, n=160):
    s = v if isinstance(v, str) else json.dumps(v, ensure_ascii=False, default=str)
    return s if len(s) <= n else s[: n - 1] + "…"


def summary(res):
    """One line for a tool result, as the trace shows it."""
    if not isinstance(res, dict):
        return short(res, 120)
    if not res.get("ok"):
        return "ok: false · " + short(res.get("error", ""), 110)
    for k in ("request_no", "po_no"):
        if res.get(k):
            return f"{res.get('po_no') or res.get('request_no')} · {res.get('status', '')}"
    if "preview" in res:
        p = res["preview"]
        val = p.get("estimated_value") or p.get("gross_value")
        return "preview · nothing saved" + (f" · £{val:,.0f}" if val else "") + (f" · approver {p['approver']}" if p.get("approver") else "")
    if "free_total" in res:
        return f"{res['free_total']:,} free · {res.get('cover_days')} days of cover"
    if "budget_left" in res:
        return f"{res.get('code')} {'open' if res.get('open') else 'CLOSED'} · £{res['budget_left']:,.0f} left"
    if "un38_3" in res:
        return f"{res.get('supplier_name')}: UN 38.3 {res['un38_3']}"
    if "matches" in res:
        return ", ".join(f"{m['name']} ({m['supplier_code']}, {m['status']})" for m in res["matches"][:2])
    if "items" in res:
        return ", ".join(i["item_code"] for i in res["items"][:3])
    if "passages" in res or "results" in res:
        return "policy passages"
    return short({k: v for k, v in res.items() if k != "ok"}, 110)


def steps_of(turn):
    out = []
    for s in turn.get("steps", []):
        if s.get("kind") == "model":
            out.append({"k": "m", "n": s["n"], "text": s.get("text", ""), "tin": s["tokens_in"], "tout": s["tokens_out"],
                        "sec": s.get("seconds"), "h": s.get("harness", []), "end": s.get("end"),
                        "calls": [{"name": c["name"], "args": c["args"], "ok": c["ok"], "blocked": c.get("blocked"),
                                   "res": summary(c.get("result")), "full": c.get("result")} for c in s.get("calls", [])]})
        else:
            out.append({"k": "h", "note": s.get("note", ""), "tool": s.get("tool"), "res": summary(s.get("result"))})
    return out


def turn_view(t):
    if not t:
        return None
    return {"text": t["text"], "reply": t["reply"], "end": t["end"], "mc": t["model_calls"], "tc": t["tool_calls"],
            "tin": t["tokens_in"], "tout": t["tokens_out"], "usd": t.get("usd"), "sec": t.get("seconds"), "steps": steps_of(t)}


def mean(xs):
    xs = [x for x in xs if x is not None]
    return round(statistics.mean(xs), 1) if xs else None


