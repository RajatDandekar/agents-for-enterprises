"""Build v5data.js (window.L2V5) for the v5 slides. Standard library only, safe on the laptop.

    python3 lectures/L2-the-brain/gen_v5data.py

  experiments/logs/tok_languages.json       Emma's question in 12 languages, four tokenizers (experiments/tok_languages.py)
  ledgerline/ledgerline/course/l2/northbridge_corpus.md   the tiny GPT's training text (course/l2/corpus.py)
  experiments/logs/tinygpt.json             the tiny GPT's run
  films/build/data/heads_data.json          what real heads do on Emma's prompt (if captured)
  the parameter counts are Qwen2.5-0.5B-Instruct's config.json shapes (they add up to the model card's 494,032,768)
"""
import json
import pathlib
import re

HERE = pathlib.Path(__file__).parent
LOGS = HERE / "experiments" / "logs"
CORPUS = HERE.parents[1] / "ledgerline" / "ledgerline" / "course" / "l2" / "northbridge_corpus.md"


def corpus_mix():
    t = CORPUS.read_text()
    paras = [p.strip() for p in t.split("\n\n") if p.strip()]
    kinds = [("stores", "Stores entries", r"^Stores,"), ("note", "Purchase notes", r"^Note,"),
             ("approval", "Approvals", r"^Approval,"), ("order", "Orders", r"^Order,"),
             ("receipt", "Goods receipts", r"^Goods receipt,"), ("reminder", "Reminders", r"^(A )?[Rr]eminder"),
             ("email", "E-mails", r"^From:"), ("policy", "Policy lines", r"^(#|\d+(\.\d+)*\s)")]
    out = {k: {"label": lab, "n": 0, "chars": 0, "example": None} for k, lab, _ in kinds}
    out["other"] = {"label": "Other short lines", "n": 0, "chars": 0, "example": None}
    for i, p in enumerate(paras):
        k = next((k for k, _, rx in kinds if re.match(rx, p)), "other")
        o = out[k]
        o["n"] += 1
        o["chars"] += len(p)
        ex = p + "\n\n" + paras[i + 1] if k == "email" else p  # an e-mail's header, then its body
        if o["example"] is None and len(ex) < 420:
            o["example"] = ex
    # one real training window, at a fixed place: 128 characters in, the same 128 shifted by one out
    i = t.index("Stores, 3 Oct 2026")
    window = t[i:i + 129]
    return {"total_chars": len(t), "paragraphs": len(paras), "kinds": out,
            "n_5400": t.count("5,400"), "window_in": window[:128], "window_out": window[1:129]}


def params():
    h, kv, m, v = 896, 128, 4864, 151936
    blk = {"q": h * h + h, "k": h * kv + kv, "v": h * kv + kv, "o": h * h,
           "gate": h * m, "up": h * m, "down": m * h, "norms": 2 * h}
    per = sum(blk.values())
    total = per * 24 + v * h + h
    assert total == 494_032_768, total
    return {"block": blk, "per_block": per, "blocks": 24, "all_blocks": per * 24, "embedding": v * h,
            "final_norm": h, "total": total, "attention": blk["q"] + blk["k"] + blk["v"] + blk["o"],
            "mlp": blk["gate"] + blk["up"] + blk["down"]}


data = {"source": "gen_v5data.py", "languages": json.loads((LOGS / "tok_languages.json").read_text()),
        "corpus": corpus_mix(), "params": params()}
tg = json.loads((LOGS / "tinygpt.json").read_text())
data["tiny"] = {k: tg[k] for k in ("config", "params", "corpus_chars", "corpus_words", "distinct_chars", "uniform_loss",
                                   "train_seconds_cpu2", "corpus_first_day", "corpus_last_day")}
heads = HERE / "films" / "build" / "data" / "heads_data.json"
if heads.exists():
    h = json.loads(heads.read_text())
    data["heads"] = {k: h[k] for k in ("examples", "summary", "source") if k in h}
out = HERE / "v5data.js"
out.write_text("/* Generated by gen_v5data.py. Do not edit by hand. */\nwindow.L2V5 = "
               + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
c = data["corpus"]
print("wrote", out.name, out.stat().st_size // 1024, "KB; corpus", {k: v["n"] for k, v in c["kinds"].items()},
      "| heads:", "yes" if "heads" in data else "not yet")
