const range = (host, label, min, max, val, step, cb, fmtv = (v) => v) => { const c = document.createElement('div'); c.className = 'ctl'; c.innerHTML = `<span>${label}</span><input type="range" min="${min}" max="${max}" step="${step}" value="${val}"><output>${fmtv(val)}</output>`; const r = c.querySelector('input'), o = c.querySelector('output'); r.oninput = (e) => { e.stopPropagation(); o.textContent = fmtv(+r.value); cb(+r.value); }; r.onclick = (e) => e.stopPropagation(); host.appendChild(c); return { set(v) { r.value = v; o.textContent = fmtv(v); } }; };
const div = (host, cls, html = '') => { const d = document.createElement('div'); if (cls) d.className = cls; d.innerHTML = html; host.appendChild(d); return d; };

