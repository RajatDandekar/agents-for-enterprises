const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const clean = (s) => String(s).replace(/[\u{1F000}-\u{1FFFF}\u{2600}-\u{27BF}]/gu, '□');
const vis = (s) => (s === null || s === undefined) ? '·' : esc(clean(s)).replace(/ /g, '␣').replace(/\n/g, '↵');
const pct = (p) => (p >= 0.1 ? (100 * p).toFixed(0) : (100 * p).toFixed(1)) + '%';
