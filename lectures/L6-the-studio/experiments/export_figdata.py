"""Copy the numbers the deck shows from experiments/logs/*.json into ../figdata.js (window.L6). Standard library only.

    python3 lectures/L6-the-studio/experiments/export_figdata.py
Every figure in figs.js reads window.L6; nothing on a plate is typed in by hand."""
import json
import pathlib

HERE = pathlib.Path(__file__).parent
LOGS = HERE / "logs"
load = lambda n: json.loads((LOGS / n).read_text()) if (LOGS / n).exists() else None


def trim(o, n=600):
    s = json.dumps(o, default=str, ensure_ascii=False)
    return o if len(s) <= n else json.loads(json.dumps({k: v for k, v in o.items() if not isinstance(v, (list, dict))}))


L6 = {"_logs": "lectures/L6-the-studio/experiments/logs/"}

p = load("probe.json")
if p:
    pick = {}
    for c in p["calls"]:
        key = (c["as"], c["tool"], json.dumps(c["args"], sort_keys=True))
        pick.setdefault(c["tool"], []).append({"as": c["as"], "args": c["args"], "result": c["result"]})
    L6["probe"] = {"scan": p["reorder_scan"], "calls": pick}

t = load("templates_fresh.json")
if t:
    L6["tpl"] = {}
    for tid, rec in t["templates"].items():
        runs = []
        for r in rec["runs"]:
            runs.append({k: r.get(k) for k in ("status", "error", "seconds", "nodes_run", "nodes_skipped", "tokens",
                                                 "cost_inr", "waited_for", "user", "reply")}
                        | {"log": [{"node": e.get("node"), "event": e.get("event"), "text": e.get("text")} for e in r["log"]],
                           "nodes": [{"id": n["id"], "status": n["status"], "summary": n.get("summary"),
                                      "seconds": n.get("seconds"), "meta": n.get("meta"),
                                      "inputs": n.get("inputs"), "output": trim(n.get("output") or {}, 900)}
                                     for n in r["nodes"]]})
        wf = rec["workflow"]
        L6["tpl"][tid] = {"name": rec["name"], "trigger": rec["trigger"], "description": wf.get("description"),
                          "nodes": [{"id": n["id"], "type": n["type"], "title": n.get("title"), "x": n.get("x"),
                                     "y": n.get("y"), "config": n.get("config")} for n in wf["nodes"]],
                          "edges": wf["edges"], "runs": runs,
                          "docs_after": {k: v for k, v in rec["docs_after"].items()}}

w = load("wf_vs_agent.json")
if w:
    L6["wva"] = {"task": w["task"], "stats": w["stats"],
                 "runs": {k: [{"i": r["i"], "correct": r["correct"], "signature": r["signature"], "told": r["told_rohit"],
                               "tool_seq": r["tool_seq"], "tokens": r["tokens"], "cost_inr": r["cost_inr"],
                               "seconds": r["seconds"], "model_calls": r["model_calls"], "turns": r.get("turns"),
                               "transcript": r.get("transcript")}
                              for r in v] for k, v in w["runs"].items()}}

TOOLBOX = HERE.parents[2] / "bahi" / "bahi" / "toolbox"
L6["services"] = {f.parent.name: json.loads(f.read_text())["services"] for f in sorted(TOOLBOX.glob("*/tool.json"))}

r = load("retry_idem.json")
if r:
    L6["retry"] = r

out = HERE.parent / "figdata.js"
out.write_text("/* generated by experiments/export_figdata.py from experiments/logs/*.json; do not edit */\n"
               "window.L6 = " + json.dumps(L6, ensure_ascii=False, default=str) + ";\n")
print(out, out.stat().st_size, "bytes;", ", ".join(k for k in L6 if not k.startswith("_")))
