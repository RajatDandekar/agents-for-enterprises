"""Copy the measured numbers from logs/*.json into the DATA block of ../figs.js (stdlib only; safe on the laptop).

    python3 lectures/L2-the-manual/experiments/figdata.py
Every number a figure draws comes from here, so a plate can always be traced to a log.
"""
import json, pathlib, re

HERE = pathlib.Path(__file__).parent
LOGS = HERE / "logs"
FIGS = HERE.parent / "figs.js"
DOCS = HERE.parents[2] / "bahi" / "bahi" / "docs"
ev = json.loads((LOGS / "retrieval_eval.json").read_text())
wk = json.loads((LOGS / "wiki_compile.json").read_text())
rv = json.loads((LOGS / "rag_vs_wiki.json").read_text())
sc = json.loads((LOGS / "scenarios_l2.json").read_text())

D = {}
D["corpus"] = [{"id": c["doc_id"], "title": c["title"], "words": c["words"], "chunks": c["chunks"],
                "tokens": wk["source_tokens"][c["doc_id"]], "audience": c["audience"], "effective": c["effective"],
                "amends": c["amends"]} for c in ev["corpus"]]
D["s1"] = ev["s1"]
D["recall"] = ev["summary"]
D["p01"] = next({m: r[m]["gold_rank"] for m in ("bm25", "vector", "hybrid", "hybrid+rerank")} for r in ev["questions"] if r["id"] == "P01")
D["m01"] = next({m: r[m]["gold_rank"] for m in ("bm25", "vector", "hybrid", "hybrid+rerank")} for r in ev["questions"] if r["id"] == "M01")
D["pca"] = {"explained": ev["pca"]["explained"], "queries": ev["pca"]["queries"],
            "points": [[p["id"], p["doc"], p["x"], p["y"], p["cos_s1"]] for p in ev["pca"]["points"]]}
D["tau"] = [{"id": r["id"], "kind": r["kind"], "top": r["tool_scores"][0]} for r in ev["questions"]]
D["leak_retrieval"] = ev["leak"]
D["wiki"] = {"pages": wk["pages"], "n_pages": wk["n_pages"], "calls": wk["compile_calls"],
             "tokens_in": wk["compile_tokens_in"], "tokens_out": wk["compile_tokens_out"], "llm_totals": wk["llm_totals"],
             "updates": wk["update_tokens"], "rag_update_chunks": wk["rag_update_chunks"], "index_tokens": wk["index_tokens"],
             "page_tokens": wk["page_tokens"], "lint": {k: (len(v) if isinstance(v, dict) else v) for k, v in wk["compile"]["lint"].items()}}
S = rv["summary"]
D["exp"] = {s: {"all": S[s]["all"], "kinds": {k: [S[s][k]["correct"], S[s][k]["n"]] for k in ("policy", "manual", "fresh", "perm", "trap")},
                "cost": S[s]["cost_inr_40"]} for s in ("closed", "full", "rag", "wiki")}
D["abl"] = {s: S[s] for s in ("rag_noperm", "rag_nofresh", "wiki_stale", "control", "wiki_control")}
D["router_v1"] = rv["router"]
D["router_v2"] = sc["router_v2"]
rows = rv["rows"]
pick = lambda sys_, qid: next(r for r in rows if r["system"] == sys_ and r["id"] == qid)
D["ex"] = {f"{s}:{q}": {"answer": pick(s, q)["answer"], "ctx": pick(s, q)["context_ids"][:6] if s != "full" else [],
                        "pages": pick(s, q).get("pages"), "tin": pick(s, q)["tokens_in"], "ok": pick(s, q)["correct"]}
           for s, q in [("closed", "P01"), ("full", "P01"), ("rag", "P01"), ("wiki", "P01"), ("wiki", "P14"), ("wiki", "P19"),
                        ("rag_noperm", "H01"), ("rag", "H01"), ("wiki_stale", "F01"), ("wiki", "F01"), ("rag", "T01"),
                        ("wiki", "T01"), ("rag", "M01"), ("wiki_control", "H01-hr"), ("rag_nofresh", "F01")]}
D["scen"] = {k: {"passed": sc[k]["result"]["passed"], "notes": sc[k]["result"]["notes"],
                 "tokens_in": sc[k]["result"]["tokens_in"], "tokens_out": sc[k]["result"]["tokens_out"],
                 "seconds": sc[k]["result"]["seconds"], "cost": sc[k]["result"]["cost_inr"],
                 "services": sc[k]["result"]["turns"][0]["services"], "reply": sc[k]["result"]["turns"][-1]["agent"],
                 "trace": sc[k]["trace"], "per_call": sc[k]["per_call_tokens_in"]} for k in ("naive", "toolloop", "policy")}
D["budget"] = sc["policy"]["context_budget"]
D["scorecard"] = [{"id": r["scenario"], "name": r["name"], "passed": r["passed"], "ne": r["never_events"], "notes": r["notes"],
                   "tokens": r["tokens_in"] + r["tokens_out"]} for r in sc["scorecard"]]
body = (DOCS / "purchase-policy.md").read_text().split("\n---", 1)[1]
D["policy_text"] = body[body.index("5.3 "):body.index("## 7.")].strip()  # §5.3–§6.4: fits the plate

src = FIGS.read_text()
block = "/* BEGIN DATA: generated by experiments/figdata.py from experiments/logs/{retrieval_eval,wiki_compile,rag_vs_wiki,scenarios_l2}.json. Do not edit by hand. */\nconst D = " + json.dumps(D, ensure_ascii=False) + ";\n/* END DATA */"
src = re.sub(r"/\* BEGIN DATA.*?/\* END DATA \*/", lambda m: block, src, flags=re.S)
FIGS.write_text(src)
print("figs.js data block:", len(block), "chars")
