"""Copy the measured numbers from experiments/logs/*.json into figs.js (between the DATA markers). Stdlib only.

    python3 lectures/L4-the-route/experiments/export_figdata.py
"""
import json
import pathlib

HERE = pathlib.Path(__file__).parent
LOGS = HERE / "logs"
FIGS = HERE.parent / "figs.js"


def load(name):
    p = LOGS / name
    return json.loads(p.read_text()) if p.exists() else None


def dedupe(path):
    out = []
    for n in path:
        if not out or out[-1] != n:
            out.append(n)
    return out


def six(name):
    d = load(name)
    if not d:
        return None
    return [{"id": r["scenario"], "name": r["name"], "passed": r["passed"], "ne": r["never_events"],
             "tokens": r["tokens_in"] + r["tokens_out"], "cost": r["cost_inr"], "seconds": r["seconds"],
             "calls": r.get("model_calls"), "tools": r.get("tool_calls"),
             "turns": [{"user": t["user"], "agent": t["agent"], "writes": t["writes"]} for t in r["turns"]],
             "path": r.get("path", []), "orders": r.get("orders", []), "new_suppliers": r.get("new_suppliers", []),
             "tool_seq": [t["tool"] for t in r.get("tool_log", [])]} for r in d["results"]]


def forty(name):
    d = load(name)
    if not d:
        return None
    rows = [{"id": r["id"], "family": r["family"], "name": r["name"], "passed": r["passed"], "ne": r["never_events"],
             "note": r["note"], "crashed": r["crashed"], "calls": r["model_calls"], "tools": r["tool_calls"],
             "services": r["services"], "tokens": r["tokens_in"] + r["tokens_out"], "cost": r["cost_inr"],
             "seconds": r["seconds"], "turns": len(r["turns"]), "gates": r["gates"],
             "detours": [n for n in dedupe(r.get("path", [])) if n in ("onboard", "fix_cost_centre", "ask_certificate",
                                                                       "approval", "hold", "answer")]}
            for r in d["results"]]
    return {"summary": d["summary"], "rows": rows}


data = {"_logs": "lectures/L4-the-route/experiments/logs/"}
data["six"] = {k: six(f"six_{k}.json") for k in ("graph", "loop", "graph_lite", "loop_lite")}
data["forty"] = {k: forty(f"forty_{k}.json") for k in ("graph", "loop", "graph_lite", "loop_lite")}

g6 = load("six_graph.json")
if g6:
    s2 = next(r for r in g6["results"] if r["scenario"] == 2)
    data["hist"] = [{"node": h["node"], "next": h["next"], "awaiting": h["awaiting"], "stage": h["stage"],
                     "draft": {k: v for k, v in h["draft"].items() if not k.startswith("flag")},
                     "facts": h["facts"]} for h in s2["history"]]
    data["decisions_s2"] = s2["decisions"]

paths = {}
for src, sid, label in (("six_graph.json", 2, "S2 · Kavita's reorder"), ("six_graph.json", 3, "S3 · Deccan Polymer Industries"),
                        ("six_graph.json", 4, "S4 · Shakti Seals, no certificate"), ("six_graph.json", 5, "S5 · whistles on PRD-05"),
                        ("six_graph.json", 1, "S1 · policy question")):
    d = load(src)
    if d:
        r = next(x for x in d["results"] if x["scenario"] == sid)
        paths[label] = {"path": r.get("path", []), "src": f"{src} · scenario {sid}", "passed": r["passed"]}
for cid, label in (("N2", "N2 · Shakti Seals, certificate given"), ("C6", "C6 · closed centre and above limit"),
                   ("D3", "D3 · blocked old Deccan code"), ("N6", "N6 · Kaveri, renewal given")):
    d = load("forty_graph.json")
    if d:
        r = next(x for x in d["results"] if x["id"] == cid)
        paths[label] = {"path": r.get("path", []), "src": f"forty_graph.json · {cid}", "passed": r["passed"]}
data["paths"] = paths

dec = load("decide_eval.json")
if dec:
    data["decide"] = {"summary": dec["summary"], "k": dec["k"],
                      "rows": [{"d": r["decision"], "input": r["input"][:90], "right": r["right"], "choice": r["choice"],
                                "conf": r["confidence"], "correct": r["correct"], "votes": r["votes"]} for r in dec["rows"]]}
mem = load("memory_turn.json")
if mem:
    data["memory"] = {t: {"scenario": mem[t]["scenario"], "next": mem[t]["next_message"],
                          "levels": {k: {"chars": v["chars"], "used_by": v["used_by"], "content": v["content"]}
                                     for k, v in mem[t]["levels"].items()}} for t in ("A", "B")}

blob = "const L4 = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";"
src = FIGS.read_text()
a, b = src.index("/* DATA:BEGIN"), src.index("/* DATA:END */")
head = src[:a] + "/* DATA:BEGIN (generated by experiments/export_figdata.py from experiments/logs/*.json; do not edit) */\n"
FIGS.write_text(head + blob + "\n" + src[b:])
print("figs.js data:", {k: (len(v) if hasattr(v, "__len__") else v) for k, v in data.items()}, f"{len(blob):,} chars")
