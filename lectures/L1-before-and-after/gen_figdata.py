"""Build figdata.js (window.L1) from this lecture's logs. Standard library only, safe on the laptop.

    python3 lectures/L1-before-and-after/gen_figdata.py

Every number a figure draws comes from here:
  experiments/logs/before_measure.json    the Before, measured through the legacy screens (two runs + traps)
  experiments/logs/after_run.json         Ask Northbridge doing the same missions (gemini-3.8-flash, toolbox over MCP)
  experiments/logs/services_blackbox.json real service requests and replies
  experiments/logs/legacy_shots.json      what each legacy screenshot shows
  ledgerline/ledgerline/toolbox/*/tool.json           the 15 tools
"""
import json
import pathlib

HERE = pathlib.Path(__file__).parent
LOGS = HERE / "experiments" / "logs"
TB = HERE.parents[1] / "ledgerline" / "ledgerline" / "toolbox"
ORDER = ["find_item", "check_stock", "find_supplier", "check_budget", "search_policy", "create_purchase_request",
         "list_my_approvals", "approve_purchase_request", "create_purchase_order", "approve_purchase_order",
         "release_purchase_order", "order_status", "receive_goods", "register_supplier", "send_message"]


def load(name):
    p = LOGS / name
    return json.loads(p.read_text()) if p.exists() else None


def trim(v, n=6):
    """Keep results readable on a plate: short lists, no huge blobs."""
    if isinstance(v, dict):
        return {k: trim(x, n) for k, x in v.items() if k not in ("python",)}
    if isinstance(v, list):
        return [trim(x, n) for x in v[:n]]
    if isinstance(v, str) and len(v) > 400:
        return v[:400] + "…"
    return v


b = load("before_measure.json")
before = {}
for run in ("first_time", "careful"):
    r = b[run]
    before[run] = {"totals": r["totals"], "klm_minutes": r["klm_minutes"], "by_person": r["by_person"],
                   "distinct_screens": r["distinct_screens"],
                   "missions": [{"id": m["id"], "title": m["title"], "counts": m["counts"],
                                 "minutes": round(m["klm_seconds"] / 60, 1), "screens": m["screens"],
                                 "errors": m["errors"]} for m in r["missions"]]}
facts = {m["id"]: m["facts"] for m in b["first_time"]["missions"]}
cfacts = {m["id"]: m["facts"] for m in b["careful"]["missions"]}
traps = b["traps"]

a = load("after_run.json")
after = []
for m in a["missions"]:
    after.append({"id": m["id"], "title": m["title"], "who": m["who"], "user": m["user"], "done": m["done"],
                  "turns": [{"user": t["user"], "reply": t["reply"], "tools": t["tools"], "seconds": t["seconds"]}
                            for t in m["turns"]],
                  "cards": [{"tool": c["tool"], "args": c["args"], "result": trim(c["result"])} for c in m["cards"]],
                  "user_turns": m["user_turns"], "taps": m["taps"], "typed_messages": m["typed_messages"],
                  "words_typed": m["words_typed"], "chars_typed": m["chars_typed"],
                  "tool_calls": m["tool_calls"], "tool_errors": m["tool_errors"], "seconds": m["seconds"]})

tools = []
for n in ORDER:
    d = json.loads((TB / n / "tool.json").read_text())
    tools.append({"name": n, "title": d["title"], "category": d["category"], "description": d["description"],
                  "writes": bool(d.get("writes")), "services": d.get("services", []),
                  "inputs": list(d["input_schema"].get("properties", {})),
                  "required": d["input_schema"].get("required", []),
                  "outputs": list(d.get("output_schema", {}).get("properties", {}))})
po_json = (TB / "create_purchase_order" / "tool.json").read_text()
po_py = (TB / "create_purchase_order" / "tool.py").read_text()

bb = load("services_blackbox.json")
shots = load("legacy_shots.json") or []

data = {
    "source": "generated by gen_figdata.py from experiments/logs/*.json",
    "before": before, "facts": facts, "careful_facts": cfacts, "traps": traps,
    "after": after, "after_model": a["model"], "after_tools_over_mcp": a["tools_discovered_over_mcp"],
    "after_summary": a["summary"], "after_cassette": a["cassette"], "after_cost_usd": a["cost_usd_total"],
    "after_ledgerline": a["ledgerline_after"], "wire": [trim(w, 3) for w in a["wire_sample"][:2]],
    "tools": tools, "po_tool_json": po_json, "po_tool_py": po_py,
    "blackbox": bb["calls"], "services_in_catalogue": bb["services_in_catalogue"],
    "shots": {s["shot"]: s for s in shots},
}
out = HERE / "figdata.js"
out.write_text("/* Generated by gen_figdata.py from experiments/logs. Do not edit by hand. */\nwindow.L1 = "
               + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
print("wrote", out, out.stat().st_size // 1024, "KB;", len(after), "missions,", len(tools), "tools,", len(shots), "shots")
