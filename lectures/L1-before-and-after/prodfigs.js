/* Part Ten figures: Ask Northbridge on industry tools (our harness, the OpenAI Agents SDK, LangGraph; traced in Langfuse)
   and the model ablation. Every number comes from window.PROD (experiments/production/figdata_production.js, generated by
   the production-tools builder's gen_figdata.py from experiments/production/logs/*.json). Screenshots are real Langfuse
   pages of those runs, in experiments/production/shots/. Nothing here is typed in by hand. */
(() => {
const FIGS = (window.FIGS = window.FIGS || {});
const P = window.PROD;
const BASE = 'experiments/production/';
const esc = (s) => String(s == null ? '' : s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
const fmt = (n) => Number(n).toLocaleString('en-GB');
const pence = (gbp) => { const p = gbp * 100; return (p >= 1 ? p.toFixed(2) : p.toFixed(3)) + 'p'; };
const todo = (el, what) => { el.innerHTML = `<div class="todo-card"><span class="todo-k">TODO(v4 data)</span><div>${what}</div><div class="todo-s">Fills from <code>experiments/production/figdata_production.js</code> (window.PROD).</div></div>`; return { step() {} }; };
const shotOf = (trace, view) => ((P && P.shots) || []).find((s) => s.trace === trace && s.view === view);
const img = (s, alt) => s ? `<img class="lf-img" src="${BASE}${esc(s.file)}" alt="${esc(alt || s.what)}" onerror="this.outerHTML='<div class=&quot;todo-card&quot;><span class=&quot;todo-k&quot;>Screenshot being retaken</span><div>${esc(s.file)}</div></div>'">` : '';

/* ---------- three runtimes, same missions (PROD.stacks) ---------- */
FIGS.prodruns = (el) => {
  if (!P || !P.stacks) return todo(el, 'The same missions on three runtimes.');
  const S = P.stacks;
  el.innerHTML = `<table class="t pr"><thead><tr><th>Runtime</th><th class="n">Passed</th><th class="n">Never-events</th><th class="n">Median tokens</th><th class="n">Model calls</th><th class="n">Cost per mission</th><th class="n">Time p50 · p95</th></tr></thead>
    <tbody>${S.map((s, i) => `<tr class="r${i}"><td><b>${esc(s.name)}</b><span class="pr-v">${esc(s.version)}</span></td><td class="n a">${s.passed}/${s.n}</td><td class="n ${s.never_events ? 'b' : 'a'}">${s.never_events}</td><td class="n">${fmt(s.median_tokens)}</td><td class="n">${s.median_model_calls}</td><td class="n">${pence(s.cost_gbp_per_mission)}</td><td class="n">${s.p50_s.toFixed(0)} s · ${s.p95_s.toFixed(0)} s</td></tr>`).join('')}</tbody></table>
    <div class="pr-same"><span class="k">The same for every run</span>${(P.meta.same_for_every_run || []).map((x) => `<span class="sk-t">${esc(x)}</span>`).join('')}<span class="sk-t">model ${esc(S[0].model)}</span></div>
    <p class="tiny" style="margin-top:10px">5 missions × 3 runs each = ${S[0].n} per runtime, ${esc((P.meta.run_dates || []).join(', '))}. Passed = every code check on Ledgerline’s tables true and no never-event. Cost = OpenRouter’s billed cost × £${P.meta.rate_gbp_per_usd}/$. Pinned: openai-agents ${esc(P.meta.versions['openai-agents'])}, langgraph ${esc(P.meta.versions.langgraph)}, langfuse ${esc(P.meta.versions.langfuse)}.</p>`;
  const rs = [...el.querySelectorAll('tbody tr')];
  return { step(k) { rs.forEach((r, i) => (r.style.opacity = i <= k ? 1 : 0.12)); } };
};

/* ---------- a real trace in Langfuse: tree, timeline, tool span, model call (PROD.shots, PROD.trace) ---------- */
FIGS.prodtrace = (el) => {
  if (!P || !P.shots) return todo(el, 'A real Ask Northbridge trace in Langfuse.');
  const V = [['tree', 'The tree'], ['span_release_purchase_order', 'A tool call'], ['timeline', 'Where the time went'], ['generation', 'One model call']];
  const src = el.dataset.trace || 'success';
  el.innerHTML = `<div class="ctl" style="margin:0 0 10px">${V.map(([v, l]) => `<button data-v="${v}">${l}</button>`).join('')}</div><div class="lf-view"></div><div class="lf-cap"></div>`;
  const view = el.querySelector('.lf-view'), cap = el.querySelector('.lf-cap'), bs = [...el.querySelectorAll('button')];
  const t = P.trace || {};
  const set = (v) => {
    const s = shotOf(src, v) || shotOf('agents_sdk', v);
    view.innerHTML = s ? img(s) : (t.svg || '');
    cap.innerHTML = s ? `${esc(s.what)} · mission ${esc(t.mission)}, ${esc(t.model)}, run ${t.run}: ${t.wall_s} s, ${fmt(t.tokens)} tokens, ${pence(t.cost_gbp)}` : '';
    bs.forEach((b) => b.classList.toggle('on', b.dataset.v === v));
  };
  bs.forEach((b) => b.addEventListener('click', () => set(b.dataset.v)));
  return { step(k) { set(V[Math.min(k, V.length - 1)][0]); } };
};

/* ---------- a never-event, caught in the trace (PROD.public_traces.failure; shots lf_failure_*) ---------- */
FIGS.prodfail = (el) => {
  const f = P && P.public_traces && P.public_traces.failure;
  if (!f) return todo(el, 'The failing trace.');
  const turn = (((P && P.shots) || []).find((x) => x.trace === 'failure' && /^turn/.test(x.view)) || {}).view || 'turn';
  const V = [[turn, 'The reply'], ['tree', 'The tree'], ['timeline', 'The timeline']];
  el.innerHTML = `<div class="ctl" style="margin:0 0 10px">${V.map(([v, l]) => `<button data-v="${v}">${l}</button>`).join('')}</div><div class="lf-view"></div><div class="lf-cap"></div>`;
  const view = el.querySelector('.lf-view'), cap = el.querySelector('.lf-cap'), bs = [...el.querySelectorAll('button')];
  const set = (v) => {
    const s = shotOf('failure', v); view.innerHTML = img(s);
    cap.innerHTML = s ? `${esc(s.what)} · ${esc(f.model)}, mission ${esc(f.mission)}, run ${f.run}${(f.never_events || []).length ? ' · ' + esc(f.never_events[0]) : ''}` : '';
    bs.forEach((b) => b.classList.toggle('on', b.dataset.v === v));
  };
  bs.forEach((b) => b.addEventListener('click', () => set(b.dataset.v)));
  return { step(k) { set(V[Math.min(k, V.length - 1)][0]); } };
};

/* fill the plates' sentences from PROD.ablation, so a re-recorded row (GPT-6 Luna) updates the words too */
if (P && P.ablation) document.addEventListener('DOMContentLoaded', () => {
  const A = P.ablation.filter((a) => a.status === 'run'), clean = A.filter((a) => a.passed === a.n && !a.never_events);
  const worst = A.slice().sort((x, y) => x.pass_rate - y.pass_rate)[0], def = A.find((a) => /course default/.test(a.kind)) || A[0];
  const cheap = clean.slice().sort((x, y) => x.cost_gbp_per_mission - y.cost_gbp_per_mission)[0];
  const r = def.cost_gbp_per_mission / cheap.cost_gbp_per_mission;
  const luna = A.find((a) => /luna/i.test(a.model));
  const lunaTxt = !luna ? '' : luna.passed < luna.n
    ? `${luna.label} passed ${luna.passed} of ${luna.n}. Its failure was our bug: receive_goods accepted the warehouse name “Manchester stores” instead of its code. Only the read-back check on Ledgerline caught it. The check on the ERP’s state caught what the reply hid.`
    : `${luna.label} passed ${luna.passed} of ${luna.n}. In an earlier sweep, before we fixed the tool, it found our bug: receive_goods accepted the warehouse name “Manchester stores” instead of its code. The check on the ERP’s state caught what the reply hid, and we fixed the tool.`;
  const V = { clean: clean.length, models: A.length, worst: worst.label,
    worst_passed: `${worst.passed} of ${worst.n}${worst.never_events ? `, with ${worst.never_events} never-event${worst.never_events > 1 ? 's' : ''}` : ''}`,
    worst_text: worst.missions_with_text_calls || 0, ratio: `1/${Math.round(r / 10) * 10}`, cheap: cheap.label, luna: lunaTxt };
  document.querySelectorAll('[data-pv]').forEach((e) => { e.textContent = V[e.dataset.pv]; });
});

/* ---------- the model ablation: one harness, six models (PROD.ablation) ---------- */
FIGS.prodablation = (el) => {
  if (!P || !P.ablation) return todo(el, 'The model ablation.');
  const A = P.ablation.filter((a) => a.status === 'run');
  const M = [
    ['pass', 'Passed and never-events', (a) => a.pass_rate, (a) => `${a.passed}/${a.n}${a.never_events ? ` · <b class="b">${a.never_events} never-event${a.never_events > 1 ? 's' : ''}</b>` : ''}`, 1],
    ['cost', 'Cost per mission', (a) => a.cost_gbp_per_mission, (a) => pence(a.cost_gbp_per_mission), null],
    ['lat', 'Time per mission, p50 (p95)', (a) => a.p50_s, (a) => `${a.p50_s.toFixed(0)} s (${a.p95_s.toFixed(0)} s)`, null],
    ['tok', 'Median tokens per mission', (a) => a.median_tokens, (a) => fmt(a.median_tokens), null],
  ];
  el.innerHTML = `<div class="ctl" style="margin:0 0 12px">${M.map(([k, l]) => `<button data-m="${k}">${l}</button>`).join('')}</div>
    <div class="ab">${A.map((a, i) => `<div class="ab-r ${a.never_events ? 'ne' : ''}" data-i="${i}"><div class="ab-n"><b>${esc(a.label)}</b><span>${esc(a.kind)}</span></div><div class="ab-tr"><span class="ab-b"></span></div><div class="ab-v"></div></div>`).join('')}</div>
    <p class="tiny" style="margin-top:12px">Our harness, the same prompt, 15 tools and five missions, three runs each (n = ${A[0].n} per model); only the model changes. Prices are OpenRouter’s list prices; cost is what was billed. Llama 4 Maverick wrote ${A.find((a) => a.tool_calls_as_text) ? A.find((a) => a.tool_calls_as_text).tool_calls_as_text : 0} tool calls as plain text instead of calling the tool.</p>`;
  const rows = [...el.querySelectorAll('.ab-r')], bs = [...el.querySelectorAll('button')];
  const set = (k) => {
    const m = M.find((x) => x[0] === k), max = m[4] || Math.max(...A.map(m[2]));
    rows.forEach((r, i) => { const a = A[i]; r.querySelector('.ab-b').style.width = (100 * m[2](a) / max) + '%'; r.querySelector('.ab-v').innerHTML = m[3](a); r.classList.toggle('bad', k === 'pass' && !!a.never_events); });
    bs.forEach((b) => b.classList.toggle('on', b.dataset.m === k));
  };
  bs.forEach((b) => b.addEventListener('click', () => set(b.dataset.m)));
  return { step(k) { set(M[Math.min(k, M.length - 1)][0]); } };
};
})();
